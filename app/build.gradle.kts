  // Release memakai keystore milik Anda bila variabel lingkungan KEYSTORE_PATH diisi.
  // Jika tidak, APK release ditandatangani dengan kunci debug bawaan Android supaya
  // tetap bisa langsung dipasang (sideload) tanpa konfigurasi tambahan.
  signingConfigs {
    val keystorePath = System.getenv("KEYSTORE_PATH")
    if (!keystorePath.isNullOrBlank()) {
      create("release") {
        storeFile = file(keystorePath)
        storePassword = System.getenv("STORE_PASSWORD")
        keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
        keyPassword = System.getenv("KEY_PASSWORD")
      }
    }
  }

  buildTypes {
    release {
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
    }
